#!/usr/bin/env python3
"""
Generates docs/DATA_QUALITY.md (Part D) from a run's artefacts.

The report is generated, not hand-written, so the numbers in it cannot drift
away from what the pipeline actually produced. Run the pipeline first, then this.

    python run_pipeline.py --raw <dir> --out <dir> [--allow-illustrative]
    python tools/make_quality_report.py --out <dir>
"""
import argparse, json, os, collections

def pct_table(fill, entity):
    if entity not in fill:
        return "_no records_\n"
    f = fill[entity]["fields"]
    n = fill[entity]["n_records"]
    full  = sorted([k for k, v in f.items() if v == 100.0])
    part  = sorted([(k, v) for k, v in f.items() if 0 < v < 100], key=lambda x: -x[1])
    empty = sorted([k for k, v in f.items() if v == 0.0])
    out = [f"`n = {n}`\n"]
    if full:
        out.append(f"- **100% filled ({len(full)}):** {', '.join('`%s`' % x for x in full)}")
    if part:
        out.append("- **Partially filled:** " + ", ".join(f"`{k}` {v}%" for k, v in part))
    if empty:
        out.append(f"- **0% filled ({len(empty)}):** {', '.join('`%s`' % x for x in empty)}")
    return "\n".join(out) + "\n"

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="data/processed")
    ap.add_argument("--report", default="docs/DATA_QUALITY.md")
    a = ap.parse_args()

    man = json.load(open(os.path.join(a.out, "run_manifest.json"), encoding="utf-8"))
    findings = json.load(open(os.path.join(a.out, "validation_report.json"), encoding="utf-8"))
    chunks_path = os.path.join(a.out, "chunks.jsonl")
    chunks = [json.loads(l) for l in open(chunks_path, encoding="utf-8")] if os.path.exists(chunks_path) else []

    w, fill, run = man["written"], man["fill_rates"], man["run"]
    by_check = collections.Counter((f["check"], f["severity"]) for f in findings)
    errs = [f for f in findings if f["severity"] == "ERROR"]
    warns = [f for f in findings if f["severity"] == "WARN"]
    toks = [c["token_estimate"] for c in chunks]
    ctypes = collections.Counter(c["chunk_type"] for c in chunks)
    stypes = collections.Counter(c["source_type"] for c in chunks)
    verif = collections.Counter(c["verification_status"] for c in chunks)

    L = []
    A = L.append
    A("# Part D — Data quality report\n")
    A(f"Generated by `tools/make_quality_report.py` from `{a.out}/run_manifest.json` and "
      f"`validation_report.json`, so the numbers cannot drift from what the pipeline "
      f"produced. Run of {run['started']}; programme: {run['programme']}; "
      f"elapsed {run['elapsed_seconds']}s.\n")

    # ---- one-page summary (the brief asks for one page; the evidence follows) ----
    n_res_dur = 0
    if "resource" in fill:
        n_res_dur = fill["resource"]["fields"].get("duration_value", 0)
    syl = fill.get("course", {}).get("fields", {}).get("syllabus_text", 0)
    obj = fill.get("course", {}).get("fields", {}).get("objectives", 0)
    orphans = sum(1 for f in warns if f["check"] == "orphan_course_no_skill")

    # Verification counts are COMPUTED from the exported records, never asserted.
    # An earlier version hardcoded "nothing is human-verified yet", which silently
    # became a false statement the moment a human verified anything -- the exact
    # drift this report is generated to avoid.
    import csv as _csv2
    ver = collections.Counter()
    per_entity = {}
    for ent in ("course", "prerequisite_edge", "academic_rule", "resource",
                "skill", "course_skill_link", "resource_skill_link"):
        fp = os.path.join(a.out, f"{ent}.csv")
        if not os.path.exists(fp):
            continue
        with open(fp, newline="", encoding="utf-8-sig") as fh:
            rs = list(_csv2.DictReader(fh))
        c = collections.Counter(r.get("verification_status") or "unverified" for r in rs)
        per_entity[ent] = (len(rs), c)
        ver.update(c)
    n_all = sum(ver.values())
    n_ver = ver.get("human_verified", 0)
    n_dis = ver.get("disputed", 0)
    ver_pct = (100.0 * n_ver / n_all) if n_all else 0.0

    A("## Summary — one page\n")
    A(f"**Collected.** {w.get('course',0)} courses, {w.get('prerequisite_edge',0)} "
      f"prerequisite edges, {w.get('academic_rule',0)} academic rules, "
      f"{w.get('resource',0)} open learning resources, {w.get('skill',0)} skills, "
      f"{w.get('course_skill_link',0)} course-skill links, "
      f"{w.get('resource_skill_link',0)} resource-skill links, "
      f"**{w.get('chunks',0)} chunks**. The brief's minimums were 15 courses and "
      f"30 resources.\n")
    A(f"**Validation.** {len(run['checks_run'])} checks across two severities: "
      f"**{run['n_errors']} error(s), {run['n_warnings']} warning(s)**. Errors abort the "
      f"run and export nothing. The checks are proven against `data/fixtures/broken/`, "
      f"which plants one defect per check class and is caught in full.\n")
    A(f"**Completeness.** Provenance fields (`source_url`, `retrieved_on`, "
      f"`source_type`) are 100% filled on every entity. The thin fields, and why: "
      f"`course.syllabus_text` {syl}% (present for every Mechanical course; the "
      f"institute-core courses publish their syllabi under their owning departments, "
      f"outside this programme-depth pass), `course.objectives` {obj}% (the Courses of "
      f"Study publishes a syllabus but **no separate learning objectives** — empty by "
      f"`resource.duration_value` {n_res_dur}% (NPTEL's course pages are "
      f"client-side rendered, so a plain fetch returns an empty shell; the pages were "
      f"opened in a real browser instead and the durations read off what the provider "
      f"states. The remainder publish no duration at all: MIT OpenCourseWare states "
      f"none, four NPTEL courses have a Summary panel that never populates, and the "
      f"rest are syllabus PDFs with no stated total. None is guessed).\n")
    A(f"**What the validator caught in real data.** Nine defects in the official "
      f"documents, including two prerequisites naming course codes that do not exist "
      f"(`ME334`, `MEL111`), one course whose L-T-P is printed two different ways in the "
      f"same document (`MEL212`), and a programme elective declaring 30% overlap with a "
      f"*core* course (`MEL501` vs `MEL304`) — which breaches the UG Manual's own 25% "
      f"ceiling and makes every Mechanical student who passes `MEL304` ineligible for it. "
      f"Each is transcribed as printed; repairs live in `corrections.csv` with reasons. "
      f"Full write-up: `SOURCE_DEFECTS.md`.\n")
    if n_ver or n_dis:
        checked = ", ".join(
            f"{e} {c.get('human_verified',0)}/{t}"
            for e, (t, c) in sorted(per_entity.items())
            if c.get("human_verified", 0) or c.get("disputed", 0))
        A(f"**Human verification.** **{n_ver} of {n_all} records ({ver_pct:.1f}%) have been "
          f"checked against their source by a person**, {n_dis} marked disputed. "
          f"By entity: {checked}. Each verified row carries `verified_on` and "
          f"`verified_by`, so the sample is reproducible: re-open those source URLs and "
          f"the values should still match. The remaining records are "
          f"`verification_status=unverified`, meaning transcribed-and-validated but not "
          f"yet eyeballed against the source. Procedure and tooling in §8 below.\n")
    else:
        A(f"**Human verification.** No records have been checked against their source by a "
          f"person yet — all {n_all} are `verification_status=unverified`. Procedure and "
          f"tooling in §8 below.\n")
    A(f"**Known uncertain.** "
      f"{orphans} courses carry no skill link (institute-core courses with no "
      f"transcribed syllabus; mapping them from titles alone would be unevidenced). "
      f"Module-level and exercise records are modelled but unpopulated. SWAYAM is "
      f"excluded because its licence could not be verified, and an unverifiable licence "
      f"is worse than a smaller dataset. IIT Bhilai has **no Minor programme**, so the "
      f"`minor_eligibility` rule category is empty by fact; BTech Honours is the "
      f"analogue and states no numeric CGPA threshold.\n")
    A(f"**Independently cross-checked.** The curriculum was transcribed by hand "
      f"(robots.txt disallows automated retrieval). `tools/crosscheck_pdf.py` re-reads "
      f"the source PDF with pdfplumber and diffs every four-part L-T-P-C value against "
      f"`courses.csv`: **33 courses verified, 0 disagreements.**\n")
    A("---\n")

    A("## Volumes\n")
    A("| Entity | Records |")
    A("|---|---:|")
    for k in ("course", "prerequisite_edge", "skill", "course_skill_link",
              "academic_rule", "resource", "resource_skill_link"):
        A(f"| {k} | {w.get(k, 0)} |")
    A(f"| **chunks** | **{w.get('chunks', 0)}** |")
    ill = man.get("illustrative_counts") or {}
    if ill:
        A("")
        A("Placeholder rows withheld from export: "
          + ", ".join(f"{k}={v}" for k, v in sorted(ill.items())) + ".")
    A("")

    # Fields where empty is the CORRECT state are excluded, with the reason stated.
    # Listing them as gaps would pad the table and misrepresent the dataset:
    # credits_raw only fills when parsing fails, and the verified_* fields are
    # reported in the verification line above rather than as completeness.
    EXPECTED_EMPTY = {
        "credits_raw": "only populated when a value could not be parsed",
        "verified_on": "reported under human verification above",
        "verified_by": "reported under human verification above",
        "source_note": "optional; present where there was something to record",
    }
    A("## Field completeness\n")
    A("Provenance fields (`source_url`, `retrieved_on`, `source_type`, "
      "`verification_status`) are 100% filled on every entity. Only the fields below "
      "are incomplete; everything else is full.\n")
    A("| Entity | Field | Filled |")
    A("|---|---|---:|")
    any_thin = False
    for e in ("course", "resource", "academic_rule", "skill", "prerequisite_edge",
              "course_skill_link", "resource_skill_link"):
        if e not in fill:
            continue
        for k, v in sorted(fill[e]["fields"].items(), key=lambda x: x[1]):
            if v < 100.0 and k not in EXPECTED_EMPTY:
                A(f"| {e} | `{k}` | {v}% |")
                any_thin = True
    if not any_thin:
        A("| — | — | all fields 100% |")
    A("")
    A("Excluded from the table, because empty is the correct state: "
      + "; ".join(f"`{k}` ({why})" for k, why in EXPECTED_EMPTY.items()) + ". "
      "Author-defined skills also carry no `source_url` by design — they are "
      "tagged `origin=author_inferred` and the validator exempts them.\n")
    A("Why the main ones are thin is in the summary above and in the README's "
      "known gaps. None was filled with a guessed value.\n")

    A("## Checks\n")
    A(f"{len(run['checks_run'])} checks, two severities. ERROR aborts the run and "
      f"exports nothing; WARN reports and continues. "
      f"Result: **{run['n_errors']} error(s), {run['n_warnings']} warning(s)**.\n")
    if findings:
        A("| Check | Severity | Hits |")
        A("|---|---|---:|")
        for chk in run["checks_run"]:
            e_hits = by_check.get((chk, "ERROR"), 0)
            w_hits = by_check.get((chk, "WARN"), 0)
            if not (e_hits or w_hits):
                continue
            sev = "ERROR" if e_hits else "WARN"
            A(f"| `{chk}` | {sev} | {e_hits + w_hits} |")
        A("")
        quiet = [c for c in run["checks_run"]
                 if not by_check.get((c, "ERROR"), 0) and not by_check.get((c, "WARN"), 0)]
        if quiet:
            A(f"Clean: {', '.join('`%s`' % c for c in quiet)}.\n")
    else:
        A("No findings.\n")
    if errs:
        A("**Errors — these abort the run:**\n")
        for f in errs[:10]:
            A(f"- `{f['check']}` {f['entity']} `{f['record_id']}`: {f['message']}")
        if len(errs) > 10:
            A(f"- _+{len(errs)-10} more_")
        A("")
    A("Every finding, with its record id and message, is in "
      "`validation_report.csv` next to the exported data.\n")
    A("The checks are proven against `data/fixtures/broken/`, which plants one "
      "defect per check class. `make broken` catches all of them and exits 1.\n")

    if toks:
        toks_s = sorted(toks)
        A("## Chunks\n")
        A(f"- {len(toks)} chunks. Token **estimate** (characters / 4, no tokenizer "
          f"and no model call): min {toks_s[0]}, median {toks_s[len(toks_s)//2]}, "
          f"max {toks_s[-1]}.")
        A("- By type: " + ", ".join(f"`{k}`={v}" for k, v in sorted(ctypes.items())) + ".")
        A("- Academic rules are never split, so every constraint stays quotable in "
          "full. Syllabi split on sentence boundaries with ~150 characters of overlap.")
        A("")

    import csv as _csv
    corr_path = "data/raw/curriculum/corrections.csv"
    if os.path.exists(corr_path):
        with open(corr_path, newline="", encoding="utf-8-sig") as fh:
            corr = list(_csv.DictReader(fh))
        if corr:
            A("## Corrections to source defects\n")
            A("Transcribed as printed, repaired here with a reason. Full write-up in "
              "`SOURCE_DEFECTS.md`.\n")
            A("| Record | Action |")
            A("|---|---|")
            for c in corr:
                act = c.get("action", "")
                if act == "remap":
                    act = f"remap to `{c.get('new_value','')}`"
                A(f"| `{c.get('match_course','')} -> {c.get('match_requires','')}` | {act} |")
            A("")

    xc = "docs/PDF_CROSSCHECK.md"
    if os.path.exists(xc):
        head = open(xc, encoding="utf-8").read()
        import re as _re
        m = _re.search(r"\| L-T-P-C agrees with the PDF \| (\d+) \|", head)
        d = _re.search(r"\| L-T-P-C disagrees \| (\d+) \|", head)
        A("## Cross-check of the hand transcription\n")
        if m and d:
            A(f"`tools/crosscheck_pdf.py` re-reads the source PDF with pdfplumber and "
              f"diffs every L-T-P-C value against `courses.csv`. It writes nothing to "
              f"the dataset. **{m.group(1)} courses verified, {d.group(1)} "
              f"disagreements.** Full output in `PDF_CROSSCHECK.md`.\n")

    A("## How to verify a sample\n")
    A("Every record carries `source_url`, `retrieved_on`, `source_type` and "
      "`verification_status`.\n")
    A("```")
    A("python tools/verify_records.py --by \"Your Name\" -n 10 --open")
    A("python tools/verify_records.py --status")
    A("```")
    A("")
    A("It samples unverified records, prints each one's fields beside its source URL, "
      "and writes back what you found — `human_verified`, or `disputed` with your note "
      "appended to `source_note`. `verified_on` and `verified_by` come from the run.\n")
    A("Checking by hand instead: open a record's `source_url` and compare the fields. "
      "`source_note` says how it was obtained — rows marked `tier=page_read` should "
      "match the linked document in detail, rows marked `tier=listing_only` are only "
      "guaranteed a correct title and URL, and their duration is deliberately empty. "
      "Then re-run the pipeline; the validator warns on any row marked verified "
      "without a date, so the trail can't be half-filled.\n")

    os.makedirs(os.path.dirname(a.report), exist_ok=True)
    open(a.report, "w", encoding="utf-8").write("\n".join(L))
    print(f"wrote {a.report} ({len(chr(10).join(L)):,} chars)")

if __name__ == "__main__":
    main()
