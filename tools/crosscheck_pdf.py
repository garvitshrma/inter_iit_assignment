#!/usr/bin/env python3
"""
Mechanically verifies the hand-transcribed courses.csv against the source PDF.

The curriculum rows were transcribed by hand (robots.txt disallows automated
retrieval, so a human downloaded the PDF). Hand transcription can go wrong, and
"trust me" is not a verification procedure. This script re-reads the PDF with
pdfplumber, pulls out every COURSE_CODE / L-T-P-C pair it can find on the
programme's structure pages, and diffs that against courses.csv.

It does NOT write to the dataset. It reports, and writes docs/PDF_CROSSCHECK.md.

    python tools/crosscheck_pdf.py
"""
import argparse, csv, os, re, sys

CODE_LTPC = re.compile(r"\b([A-Z]{2,4})\s*(\d{3})\b[^0-9\n]{0,60}?"
                       r"(\d+(?:\.\d+)?-\d+(?:\.\d+)?-\d+(?:\.\d+)?-\d+(?:\.\d+)?)")
CODE_ONLY = re.compile(r"\b([A-Z]{2,4}\d{3})\b")


LTPC_ANY = re.compile(r"\d+(?:\.\d+)?-\d+(?:\.\d+)?-\d+(?:\.\d+)?-\d+(?:\.\d+)?")


def find_programme_pages(pdf, heading, window):
    """
    The heading also appears in the table of contents, where there is no course
    table at all -- so a naive first-match lands on page 2 and finds nothing.
    Require the page to carry both the heading AND at least one four-part L-T-P-C
    value, which only the real structure pages do.
    """
    for i, page in enumerate(pdf.pages):
        t = page.extract_text() or ""
        if heading.lower() in t.lower() and LTPC_ANY.search(t):
            return list(range(i, min(i + window, len(pdf.pages))))
    return []


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pdf", default="data/raw/curriculum/Courses_Of_Study.pdf")
    ap.add_argument("--csv", default="data/raw/curriculum/courses.csv")
    ap.add_argument("--heading", default="BTech in Mechanical Engineering")
    ap.add_argument("--window", type=int, default=3, help="pages to scan from the heading")
    ap.add_argument("--report", default="docs/PDF_CROSSCHECK.md")
    a = ap.parse_args()

    try:
        import pdfplumber
    except ImportError:
        sys.exit("pdfplumber not installed: pip install -r requirements.txt")
    if not os.path.exists(a.pdf):
        sys.exit(f"{a.pdf} not found")

    with open(a.csv, newline="", encoding="utf-8-sig") as fh:
        rows = list(csv.DictReader(fh))
    csv_ltpc, csv_credits = {}, {}
    for r in rows:
        code = r["code"].strip()
        m = re.match(r"^(\d+(?:\.\d+)?)-(\d+(?:\.\d+)?)-(\d+(?:\.\d+)?)-(\d+(?:\.\d+)?)$",
                     (r["credits"] or "").strip())
        if m:
            csv_ltpc[code] = m.group(0)
            csv_credits[code] = float(m.group(4))

    pdf_ltpc, pages_scanned = {}, []
    with pdfplumber.open(a.pdf) as pdf:
        pages = find_programme_pages(pdf, a.heading, a.window)
        if not pages:
            sys.exit(f"heading {a.heading!r} not found in {a.pdf}")
        for i in pages:
            pages_scanned.append(i + 1)
            text = pdf.pages[i].extract_text() or ""
            flat = re.sub(r"[ \t]+", " ", text)
            for dept, num, ltpc in CODE_LTPC.findall(flat):
                pdf_ltpc.setdefault(f"{dept}{num}", set()).add(ltpc)

    agree, disagree, pdf_only, csv_only = [], [], [], []
    for code, found in sorted(pdf_ltpc.items()):
        if code not in csv_ltpc:
            pdf_only.append((code, sorted(found)))
        elif csv_ltpc[code] in found:
            agree.append((code, csv_ltpc[code]))
        else:
            disagree.append((code, csv_ltpc[code], sorted(found)))
    for code in sorted(csv_ltpc):
        if code not in pdf_ltpc:
            csv_only.append(code)

    L = ["# PDF cross-check — hand transcription vs. source PDF\n",
         f"Generated by `tools/crosscheck_pdf.py`. Source: `{a.pdf}`, "
         f"pages {pages_scanned} (located by searching for the heading "
         f"\"{a.heading}\"). Compared against `{a.csv}`.\n",
         "This is a **mechanical re-read of the PDF**, independent of the hand "
         "transcription. It writes nothing to the dataset.\n",
         "## Summary\n",
         f"| Outcome | Count |", "|---|---:|",
         f"| L-T-P-C agrees with the PDF | {len(agree)} |",
         f"| L-T-P-C disagrees | {len(disagree)} |",
         f"| Found in PDF, absent from courses.csv | {len(pdf_only)} |",
         f"| In courses.csv, not found on the scanned pages | {len(csv_only)} |", ""]

    if disagree:
        L += ["## Disagreements — review these first\n",
              "| Course | courses.csv | PDF |", "|---|---|---|"]
        L += [f"| `{c}` | `{v}` | {', '.join('`%s`' % x for x in f)} |" for c, v, f in disagree]
        L.append("")
    else:
        L += ["## Disagreements\n", "None. Every L-T-P-C value the parser could read off the "
              "scanned pages matches the hand transcription.\n"]

    if pdf_only:
        L += ["## In the PDF but not in courses.csv\n",
              "Expected: the structure pages are printed as side-by-side columns, so codes "
              "belonging to the facing programme's table bleed into the same extracted page "
              "text. Codes below that are not Mechanical programme courses are correctly "
              "absent from the dataset.\n",
              "| Course | L-T-P-C in PDF |", "|---|---|"]
        L += [f"| `{c}` | {', '.join('`%s`' % x for x in f)} |" for c, f in pdf_only]
        L.append("")

    if csv_only:
        L += ["## In courses.csv but not found on the scanned pages\n",
              "Expected for the programme electives and for any course whose credits are "
              "printed in the prose form (\"3 Credits (2-1-0)\") in the course-description "
              "section rather than as an L-T-P-C cell in the structure table. The parser only "
              "matches the four-part table form.\n",
              "Codes: " + ", ".join(f"`{c}`" for c in csv_only) + "\n"]

    os.makedirs(os.path.dirname(a.report), exist_ok=True)
    open(a.report, "w", encoding="utf-8").write("\n".join(L))
    print(f"pages scanned: {pages_scanned}")
    print(f"agree: {len(agree)}   disagree: {len(disagree)}   "
          f"pdf-only: {len(pdf_only)}   csv-only: {len(csv_only)}")
    for c, v, f in disagree:
        print(f"  DISAGREE {c}: csv={v} pdf={f}")
    print(f"wrote {a.report}")
    return 1 if disagree else 0


if __name__ == "__main__":
    sys.exit(main())
